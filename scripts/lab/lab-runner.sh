#!/bin/bash
# Прогоняет один эксперимент по bring-up'у на загруженном устройстве.
#
# Зачем это вообще: у телефона под нашим ядром нет ни adb, ни serial, ни
# сети. Прошлая попытка UFS утонула именно в этом — драйвер подвешивал
# систему каждый раз в новом месте, и единственным источником данных были
# фотографии экрана. Теперь под нами полноценный Debian на карте, так что
# эксперимент можно запускать сам собой при загрузке, а результат забирать
# после перезагрузки в TWRP.
#
# Три независимых канала записи, потому что зависание съедает буферы:
#   1. /var/log/dreamlte/<стамп>.log  — с fsync после каждой строки;
#   2. /dev/kmsg                      — попадает в ramoops, переживает
#                                       тёплый ребут даже при мёртвой ФС;
#   3. journal                        — читаемый, но менее надёжный.
#
# Эксперимент берётся из /root/lab/experiment.sh и запускается ТОЛЬКО если
# лежит флаг /root/lab/ARMED. Флаг снимается ДО запуска: если эксперимент
# подвесит телефон, следующая загрузка будет чистой, а не уйдёт в петлю
# "загрузился → повис → перезагрузился → повис".
set -u

LAB=/root/lab
LOGDIR=/var/log/dreamlte
STAMP="$(date +%Y%m%d-%H%M%S)"
LOG="$LOGDIR/$STAMP.log"

mkdir -p "$LOGDIR"

say() {
	# Каждая строка идёт разом во все три канала и тут же на диск.
	echo "[lab] $*" >> "$LOG"
	echo "[lab] $*" > /dev/kmsg 2>/dev/null
	logger -t dreamlte-lab -p crit "$*" 2>/dev/null
	sync
}

# --- Разбор прошлой загрузки ------------------------------------------
# systemd-pstore уже перенёс сюда всё, что ядро оставило в ramoops перед
# прошлым падением/зависанием. Если файлы есть — прошлый прогон умер, и
# вот его последние слова.
PSTORE=/var/lib/systemd/pstore
if [ -d "$PSTORE" ] && [ -n "$(ls -A "$PSTORE" 2>/dev/null)" ]; then
	say "=== есть данные ramoops с прошлой загрузки ==="
	find "$PSTORE" -type f -newermt "-2 days" | while read -r f; do
		say "--- $f ---"
		cat "$f" >> "$LOG"
	done
	sync
fi

if [ ! -f "$LAB/ARMED" ]; then
	say "эксперимент не взведён (нет $LAB/ARMED) — ничего не делаю"
	exit 0
fi

# Снимаем флаг ДО запуска и дожидаемся записи на диск.
rm -f "$LAB/ARMED"
sync

if [ ! -x "$LAB/experiment.sh" ]; then
	say "флаг был, а $LAB/experiment.sh нет или он не исполняемый"
	exit 1
fi

say "=========================================================="
say "эксперимент СТАРТ: $STAMP"
say "ядро: $(uname -r)"
say "=========================================================="

# Сам эксперимент — в подоболочке, чтобы его вывод тоже шёл в лог с
# синхронизацией. stdbuf -o0: буферизация здесь означает потерю ровно тех
# строк, ради которых всё и затевалось.
stdbuf -o0 -e0 "$LAB/experiment.sh" 2>&1 | while IFS= read -r line; do
	echo "$line" >> "$LOG"
	echo "$line" > /dev/kmsg 2>/dev/null
	sync
done

say "=========================================================="
say "эксперимент ЗАВЕРШИЛСЯ САМ (не повис): $STAMP"
say "=========================================================="
