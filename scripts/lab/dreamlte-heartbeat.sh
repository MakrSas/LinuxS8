#!/bin/bash
# Пульс: раз в секунду пишет на карту время работы системы.
#
# Отвечает на вопрос, который прошлый заход по UFS так и не смог закрыть:
# когда телефон "завис" — умерло ядро целиком или только вывод на экран?
# Пользователь тогда заметил, что курсор перестаёт мигать, и предположил,
# что живо может быть и то и другое, а проверить было нечем.
#
# Теперь проверить есть чем. Если после запуска эксперимента экран замер, а
# файл пульса продолжал расти — ядро было живо, и мы искали не то. Если
# пульс оборвался ровно на эксперименте — зависла система.
set -u

OUT=/var/log/dreamlte/heartbeat
mkdir -p "$(dirname "$OUT")"

# Отдельный файл на каждую загрузку, иначе не отличить старый пульс от
# нового после форс-ребута.
BOOT="$(date +%Y%m%d-%H%M%S)"
echo "=== boot $BOOT ===" >> "$OUT"
sync

while true; do
	# uptime, а не дату: RTC у этого устройства в mainline нет, часы
	# стартуют из эпохи и время идёт неверное — а вот монотонный uptime
	# честно показывает, сколько система реально прожила.
	printf '%s uptime=%s\n' "$BOOT" "$(cut -d' ' -f1 /proc/uptime)" >> "$OUT"
	sync
	sleep 1
done
