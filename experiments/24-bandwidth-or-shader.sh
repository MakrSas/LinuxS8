#!/bin/bash
# Эксперимент 24: упор в память или в вычисления.
#
# Опыт 23 опроверг мою версию про частоту. GPU переведён с 200 на 400 МГц
# (подтверждено по clk_summary), а пропускная способность на лёгком шейдере
# осталась ровно той же: 405.9 против 405.2 Мпикс/с. Значит на такой
# нагрузке упор не в шейдерные ядра.
#
# 405 Мпикс/с по 4 байта — это 1.6 ГБ/с записи, и число держится на двух
# разных размерах буфера и двух разных частотах. Так ведёт себя потолок
# памяти, а не вычислителя.
#
# Проверка прямая: то же самое, но в буфер RGB565 — два байта на пиксель
# вместо четырёх.
#
#   пикселей в секунду вырастет примерно вдвое  -> упор в байты,
#     и дальше надо смотреть на частоты CORE и MIF, которых мы никогда
#     не касались (у вендора ими управляет ACPM, в mainline его нет);
#
#   останется прежней                           -> упор в число пикселей,
#     версия про память неверна, ищем дальше.
#
# Для полноты — тот же прогон с тяжёлым шейдером: там упор должен быть в
# вычисления, и формат не должен менять почти ничего. Если поменяет —
# значит я неправильно понимаю всю картину.
set -u

BIN=/root/lab/gputest

echo "############ ЭКСПЕРИМЕНТ 24: память или вычисления ############"
echo "uptime: $(cut -d' ' -f1 /proc/uptime)"
dmesg -n 4

modprobe --ignore-install panfrost 2>/dev/null || true
sleep 2

echo ""
echo "--- частота GPU ---"
grep -E "gout_g3d_agpu" /sys/kernel/debug/clk/clk_summary 2>/dev/null \
	| awk '{printf "  %s = %s Гц\n", $1, $5}'

MAJMIN=$(stat -c '%t %T' /dev/dri/renderD128)
MAJ=$(printf '%d' 0x$(echo "$MAJMIN" | cut -d' ' -f1))
MIN=$(printf '%d' 0x$(echo "$MAJMIN" | cut -d' ' -f2))

run() { # $1=w $2=h $3=iters $4=fmt565 $5=подпись
	echo ""
	echo "--- ${1}x${2}, тяжесть $3, $5 ---"
	unshare -m sh -c "
		mount -t tmpfs -o dev,mode=0755 tmpfs /dev/dri &&
		mknod /dev/dri/renderD128 c $MAJ $MIN &&
		chmod 666 /dev/dri/renderD128 &&
		EGL_PLATFORM=surfaceless timeout 180 $BIN 20 $3 $1 $2 0 $4
	" 2>&1 | grep -aE "формат цели|рисование|кадров/с|Мпикс/с|ГБ/с"
}

echo ""
echo "=============================================================="
echo "ЛЁГКИЙ ШЕЙДЕР — здесь и должен быть виден упор в память"
echo "=============================================================="
run 1440 2960 1 0 "RGBA8888"
run 1440 2960 1 1 "RGB565"
run 2048 2048 1 0 "RGBA8888"
run 2048 2048 1 1 "RGB565"

echo ""
echo "=============================================================="
echo "ТЯЖЁЛЫЙ ШЕЙДЕР — здесь формат почти не должен влиять"
echo "=============================================================="
run 1440 2960 16 0 "RGBA8888"
run 1440 2960 16 1 "RGB565"

echo ""
echo "--- dmesg ---"
dmesg | grep -aiE "panfrost|sched timeout|Soft-stop" | tail -8
echo "############ КОНЕЦ 24 ############"
