#!/bin/bash
# Эксперимент 30: откуда берётся низкая частота кадров.
#
# Что уже точно известно и повторно не проверяется:
#  - GPU не узкое место: полноэкранный проход стоит около 0.43 мс;
#  - чтение кадра обратно в память идёт 26 МБ/с, то есть композитор так
#    не делает — иначе было бы 1.6 кадра в секунду, а не 25;
#  - phoc действительно рисует на GPU: в журнале "GL renderer: Mali-G71
#    MC20 (Panfrost)", то есть композитинг аппаратный.
#
# Остаются два подозреваемых, и оба меряются здесь.
#
# ПЕРВЫЙ — доставка кадра на экран. Настоящего KMS у нас нет, есть
# simpledrm поверх буфера загрузчика. Переключения буферов там не бывает:
# на каждом коммите ядро копирует кадр в память экрана процессором. Это
# обязательный расход на кадр, и он задаёт потолок независимо от GPU.
# fbbench меряет его напрямую, без композитора.
#
# ВТОРОЙ — дробный масштаб. В журнале прошлой загрузки нашлось
# "Adjusting output scale from 3.074219 to 3.075000": пользователь выбрал
# в настройках 300%, а получилось дробное число. GTK3, на котором написана
# вся оболочка, дробный масштаб не умеет вовсе — phoc выдаёт таким
# клиентам ближайшее целое сверху (4) и потом ужимает картинку. Это 1.7
# раза лишних пикселей плюс пересэмплирование каждого кадра.
#
# Меряем один и тот же клиент при 1, 2, 3 и 3.075. Если дробный масштаб
# заметно хуже соседнего целого — виноват он, и лечится это строкой в
# конфиге. Если разницы нет — виновата копия, и лечится она только
# настоящим драйвером дисплея.
set -u

LAB=/root/lab
SRC=/root/lab/fbbench.c
BIN=/root/lab/fbbench
RD=/run/user/1000

resets() { dmesg 2>/dev/null | grep -ac "sched timeout" || true; }

wayland_socket() {
	local w
	w=$(ls -1 "$RD"/wayland-[0-9]* 2>/dev/null | grep -v '\.lock$' | head -1)
	[ -n "$w" ] && basename "$w"
}

echo "############ ЭКСПЕРИМЕНТ 30: масштаб и копия кадра ############"
echo "uptime: $(cut -d' ' -f1 /proc/uptime)"

echo ""
echo "=============================================================="
echo "ЧАСТЬ 1: сколько стоит копия кадра в память экрана"
echo "=============================================================="
# Замер не портит картинку: fbbench считывает текущее содержимое экрана и
# пишет обратно ровно те же байты.
# cc в rootfs нет — только gcc, поэтому берём первый попавшийся.
CC=$(command -v cc || command -v gcc || command -v aarch64-linux-gnu-gcc || true)
if [ -n "$CC" ] && [ -f "$SRC" ]; then
	echo "компилятор: $CC"
	"$CC" -O2 -o "$BIN" "$SRC" 2>&1 | head -5
else
	echo "!! компилятора нет: CC='$CC'"
fi
if [ -x "$BIN" ]; then
	timeout 120 "$BIN" 20 2>&1
else
	echo "!! fbbench не собрался"
fi

echo ""
echo "=============================================================="
echo "ЧАСТЬ 2: частота кадров при разных масштабах"
echo "=============================================================="
echo ">>> жду 75 с, пока phosh поднимется"
sleep 75

phase() { # $1=подпись $2=аргумент помощника
	local tag="$1" arg="$2" r0 r1 wd
	echo ""
	echo "--------------------------------------------------------------"
	echo "масштаб: $tag"
	echo "--------------------------------------------------------------"

	timeout 60 /usr/local/bin/dreamlte-switch-shell "$arg" 2>&1 | head -3
	sleep 60

	wd=$(wayland_socket)
	if [ -z "$wd" ]; then
		echo "  !! сокета Wayland нет, оболочка не поднялась"
		return
	fi
	echo "  сокет: $wd"

	# Что phoc в итоге применил — берём из его же журнала, а не из конфига.
	journalctl -b --no-pager -t phoc 2>/dev/null \
		| grep -aE "Adjusting output scale|Modesetting with" | tail -2 \
		| sed 's/^/  /'

	r0=$(resets)
	su phone -c "XDG_RUNTIME_DIR=$RD WAYLAND_DISPLAY=$wd \
		timeout 120 glmark2-es2-wayland -b build:duration=6 -b texture:duration=6" 2>&1 \
		| grep -aE "Surface Size|^\[|glmark2 Score" | sed 's/^/  /'
	r1=$(resets)
	echo "  сбросов GPU за прогон: $((r1 - r0))"
}

phase "1 (без масштаба)"        scale1
phase "2 (целый)"               scale2
phase "3 (целый)"               scale3
phase "3.075 (дробный)"         scale-frac

echo ""
echo ">>> возвращаю целый масштаб 3"
timeout 60 /usr/local/bin/dreamlte-switch-shell scale3 2>&1 | head -2
sleep 30

echo ""
echo "--- dmesg по GPU ---"
dmesg | grep -aiE "panfrost|sched timeout" | tail -8
sync
echo "############ КОНЕЦ 30 ############"
