#!/bin/bash
# Эксперимент 22: задания GPU слишком долгие или ломаются по размеру?
#
# В опыте 21 нашёлся порог: до 1440x1440 (2.07 Мпикс) кадр рисуется верно,
# с 2048x2048 (4.19 Мпикс) — уже нет, причём уцелевает нижняя часть, а
# выше идут нули. Ядро при этом печатает:
#
#   panfrost: gpu sched timeout, js=0, status=0x8, head=tail
#   panfrost: Soft-stop failed
#
# То есть задание не завершается, снимается по таймауту (у panfrost он
# 500 мс), и кадр остаётся недорисованным. AFBC проверен и оправдан: с ним
# и без него одинаково.
#
# Осталось различить две причины, и они требуют разного лечения:
#
#   ДОЛГО   — работа не укладывается в 500 мс. Тогда с лёгким шейдером
#             тот же размер пройдёт, а лечится это частотой GPU: сейчас
#             200 МГц, вендорская таблица PLL_G3D даёт до 860.
#
#   СЛОМАНО — размер сам по себе валит задание, сколько бы работы в нём
#             ни было. Тогда лёгкий шейдер не спасёт, и копать надо в
#             сторону тайлера и его кучи.
#
# Меряем на одном размере 2048x2048, меняя только тяжесть шейдера.
# Чтение кадра отключено (пятый аргумент 0): оно идёт со скоростью 26 МБ/с
# и на таких буферах занимает секунды, забивая замер.
set -u

BIN=/root/lab/gputest

echo "############ ЭКСПЕРИМЕНТ 22: таймаут или размер ############"
echo "uptime: $(cut -d' ' -f1 /proc/uptime)"
dmesg -n 4

modprobe --ignore-install panfrost 2>/dev/null || true
sleep 2

echo ""
echo "--- частота GPU ---"
grep -E "gout_g3d_agpu" /sys/kernel/debug/clk/clk_summary 2>/dev/null \
	| awk '{printf "  %s = %s Гц\n", $1, $5}'

MAJMIN=$(stat -c '%t %T' /dev/dri/renderD128)
MAJ=$(printf '%d' 0x$(echo "$MAJMIN" | cut -d' ' -f1))
MIN=$(printf '%d' 0x$(echo "$MAJMIN" | cut -d' ' -f2))

run() { # $1=w $2=h $3=iters
	echo ""
	echo "--- ${1}x${2}, тяжесть шейдера $3 ---"
	dmesg -c >/dev/null 2>&1 || true
	unshare -m sh -c "
		mount -t tmpfs -o dev,mode=0755 tmpfs /dev/dri &&
		mknod /dev/dri/renderD128 c $MAJ $MIN &&
		chmod 666 /dev/dri/renderD128 &&
		EGL_PLATFORM=surfaceless timeout 180 $BIN 20 $3 $1 $2 0
	" 2>&1 | grep -aE "центр|лев\.|прав\.|рисование|кадров/с|Мпикс/с"
	n=$(dmesg 2>/dev/null | grep -ac "sched timeout" || true)
	echo "  таймаутов GPU за этот прогон: ${n:-0}"
}

echo ""
echo "=============================================================="
echo "ЛЁГКИЙ ШЕЙДЕР НА БОЛЬШОМ БУФЕРЕ — главный вопрос опыта"
echo "=============================================================="
for it in 1 4 16 32 64; do
	run 2048 2048 "$it"
done

echo ""
echo "=============================================================="
echo "Полный экран с самым лёгким шейдером"
echo "=============================================================="
run 1440 2960 1

echo ""
echo "=============================================================="
echo "Контроль: размер, который заведомо работал"
echo "=============================================================="
run 1440 1440 64

echo ""
echo "--- dmesg целиком ---"
dmesg | grep -aiE "panfrost|gpu fault|MMU|sched|reset|Soft-stop" | tail -20
echo "############ КОНЕЦ 22 ############"
