#!/bin/bash
# Эксперимент 19: какой на самом деле координатный диапазон у тачскрина.
#
# Хватит гадать. Контроллер свой размер не сообщает (драйвер пишет "the
# axis have not been set"), а подбор вслепую уже стоил одного цикла:
# значения 1440x2960, взятые от STM-варианта, обрезали всё дальше ~35%
# экрана, и телефон перестал разблокироваться.
#
# Здесь диапазон ИЗМЕРЯЕТСЯ. Ядро значения в ABS-событиях не обрезает по
# объявленному максимуму, так что записанные сырые числа показывают
# настоящее поле контроллера независимо от того, что стоит в dts.
#
# ОТ ПОЛЬЗОВАТЕЛЯ нужно: пока идёт запись (45 секунд), провести пальцем по
# всему экрану — обязательно до самых углов и по всем четырём краям.
# Экран в это время может не реагировать, это нормально: мы читаем события
# напрямую с устройства, а не через оболочку.
set -u

DEV=/dev/input/event0
SECS=45

echo "############ ЭКСПЕРИМЕНТ 19: диапазон тачскрина ############"
echo "uptime: $(cut -d' ' -f1 /proc/uptime)"

echo ""
echo "=== что объявлено сейчас ==="
timeout 3 evtest "$DEV" 2>&1 | sed -n '/Input device name/p;/ABS_MT_POSITION/,+4p' | head -20

echo ""
echo "=== что говорит драйвер ==="
dmesg | grep -aiE "s6sy761" | tail -5

echo ""
echo "=============================================================="
echo "  ВОДИ ПАЛЬЦЕМ ПО ВСЕМУ ЭКРАНУ $SECS СЕКУНД, ДО САМЫХ УГЛОВ"
echo "=============================================================="
timeout "$SECS" evtest "$DEV" > /tmp/touch-raw.txt 2>&1 || true
echo "записано строк: $(wc -l < /tmp/touch-raw.txt)"

echo ""
echo "=== измеренный диапазон ==="
awk '
/ABS_MT_POSITION_X/ { v=$NF+0; if (nx++==0){minx=maxx=v} if(v<minx)minx=v; if(v>maxx)maxx=v }
/ABS_MT_POSITION_Y/ { v=$NF+0; if (ny++==0){miny=maxy=v} if(v<miny)miny=v; if(v>maxy)maxy=v }
END {
  if (nx) printf "  X: %d значений, от %d до %d\n", nx, minx, maxx;
  else    printf "  X: событий не было\n";
  if (ny) printf "  Y: %d значений, от %d до %d\n", ny, miny, maxy;
  else    printf "  Y: событий не было\n";
  print "";
  print "  Для сверки: панель 1440x2960.";
  print "  Если максимумы около 4095 — поле контроллера 4096x4096 (вариант Samsung).";
  print "  Если около 1439/2959 — поле в пикселях панели (вариант STM).";
}' /tmp/touch-raw.txt

echo ""
echo "=== первые события для наглядности ==="
grep -aE "ABS_MT_POSITION|ABS_MT_TRACKING" /tmp/touch-raw.txt | head -12

echo "############ КОНЕЦ 19 ############"
