#!/bin/bash
# Эксперимент 25: расход на кадр постоянный или зависит от пикселей?
#
# Опыт 24 опроверг версию про пропускную способность памяти: вдвое меньше
# байт на пиксель — та же скорость в пикселях. Зато обнажил другое.
#
# Смотреть надо было не на пиксели, а на КАДРЫ:
#
#   2048x2048  -> 96.3 кадра/с
#   1440x2960  -> 95.0 кадра/с
#
# Разные буферы, разные форматы, две разные частоты GPU (200 и 400 МГц) —
# а частота кадров держится около 95, то есть 10.5 мс на кадр. Так себя
# ведёт не работа с пикселями, а постоянный расход на кадр.
#
# Здесь это проверяется в лоб: тот же лёгкий шейдер на буферах от 128x128
# до полноэкранного.
#
#   везде около 95 кадров        -> расход фиксированный, и вся возня с
#                                   пикселями, байтами и частотой била мимо;
#   на мелких буферах тысячи     -> расход пропорционален пикселям,
#                                   след ложный, ищем дальше.
#
# Плюс честное сравнение, которого не хватило в прошлый раз: там я менял
# разом и формат, и тип вложения. Теперь RGBA8888 прогоняется и текстурой,
# и renderbuffer'ом — при одном формате видно вклад именно вложения.
set -u

BIN=/root/lab/gputest

echo "############ ЭКСПЕРИМЕНТ 25: постоянный расход на кадр ############"
echo "uptime: $(cut -d' ' -f1 /proc/uptime)"
dmesg -n 4

modprobe --ignore-install panfrost 2>/dev/null || true
sleep 2

MAJMIN=$(stat -c '%t %T' /dev/dri/renderD128)
MAJ=$(printf '%d' 0x$(echo "$MAJMIN" | cut -d' ' -f1))
MIN=$(printf '%d' 0x$(echo "$MAJMIN" | cut -d' ' -f2))

run() { # $1=w $2=h $3=target $4=кадров
	echo ""
	echo "--- ${1}x${2} ---"
	unshare -m sh -c "
		mount -t tmpfs -o dev,mode=0755 tmpfs /dev/dri &&
		mknod /dev/dri/renderD128 c $MAJ $MIN &&
		chmod 666 /dev/dri/renderD128 &&
		EGL_PLATFORM=surfaceless timeout 180 $BIN ${4:-100} 1 $1 $2 0 $3
	" 2>&1 | grep -aE "цель |рисование|кадров/с|Мпикс/с"
}

echo ""
echo "=============================================================="
echo "ГЛАВНОЕ: лёгкий шейдер от крошечного буфера до полноэкранного"
echo "=============================================================="
run 128 128 0 500
run 256 256 0 500
run 512 512 0 300
run 1024 1024 0 200
run 2048 2048 0 100
run 1440 2960 0 100

echo ""
echo "=============================================================="
echo "ЧЕСТНОЕ СРАВНЕНИЕ: один формат, разный тип вложения"
echo "=============================================================="
echo ">>> RGBA8888 в текстуре"
run 1440 2960 0 60
echo ">>> RGBA8888 в renderbuffer"
run 1440 2960 2 60
echo ">>> RGB565 в renderbuffer"
run 1440 2960 1 60

echo ""
echo "--- dmesg ---"
dmesg | grep -aiE "panfrost|sched timeout|Soft-stop" | tail -8
echo "############ КОНЕЦ 25 ############"
