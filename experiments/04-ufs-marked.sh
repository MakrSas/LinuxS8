#!/bin/bash
# Эксперимент 04: загрузить UFS на ядре с «медленными» маркерами.
#
# Ядро пересобрано: каждый маркер трассировки теперь после печати крутит
# mdelay(60), давая fbcon дорисовать строку. Значит последняя видимая на
# экране строка — действительно последняя выполненная, а не последняя
# успевшая отрисоваться. На этом мы уже обманулись один раз: экран
# показывал остановку в ufshcd_alloc_host(), где нет ни одного обращения
# к железу.
#
# От скрипта тут почти ничего не требуется — вся диагностика в ядре.
# Задача одна: загрузить модули и не мешать. Смотреть надо на ЭКРАН.
set -u

MODDIR="/lib/modules/$(uname -r)/kernel"

echo "############ ЭКСПЕРИМЕНТ 04 ############"
echo "смотреть на экран телефона: маркеры UFSTRACE идут по одному в 60 мс"
echo "uptime: $(cut -d' ' -f1 /proc/uptime)"
sync

# Консоль должна печатать всё: маркеры это pr_emerg, они проходят при любом
# уровне, но дальше пойдут и обычные сообщения драйвера.
dmesg -n 7

echo ">>> phy-exynos-ufs"
insmod "$MODDIR/drivers/phy/samsung/phy-exynos-ufs.ko" || echo "  PHY rc=$?"
sleep 3
sync

echo ">>> ufs-exynos"
insmod "$MODDIR/drivers/ufs/host/ufs-exynos.ko" || echo "  UFS rc=$?"
RC=$?
sync

echo "<<< вернулся, rc=$RC"
sleep 2
dmesg | tail -50
grep -E "sd[a-z]" /proc/partitions || echo "  блочных устройств нет"
echo "############ КОНЕЦ 04 ############"
