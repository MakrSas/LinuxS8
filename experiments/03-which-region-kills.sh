#!/bin/bash
# Эксперимент 03: какая из областей регистров UFS вешает SoC.
#
# Почему без драйвера. Опыт 02 показал две вещи:
#   * между "P2 get_irq done" и "P3" стоит ufshcd_alloc_host() — чистая
#     софтверная функция (scsi_host_alloc, devres, init списков), ни одного
#     обращения к железу. Заморозить SoC там нечему. Значит выполнение ушло
#     ДАЛЬШЕ, а консоль просто отстала: маркеры идут через 133 мкс, fbcon на
#     1440x2960 столько не может. Экран — нижняя граница, а не факт.
#   * система умирает через ~0.3 мс после начала probe. Никакой опрос из
#     userspace такую гонку не выигрывает.
#
# Значит надо убрать драйвер из уравнения. В device tree у узла ufs четыре
# области регистров, и они обслуживаются разными тактами:
#
#     hci     0x11120000  ядро контроллера      (core_clk — заведомо жив,
#                                                читался как 0x1303FF0F)
#     vs_hci  0x11121100  вендорские регистры
#     unipro  0x11110000  блок UniPro           (sclk_unipro_main)
#     ufsp    0x11130000  блок защиты (FMP)
#
# Классическая причина мёртвого зависания всего SoC на Exynos — обращение к
# блоку, которому не подан такт: транзакция на шине не завершается никогда,
# и ядро висит на ней без исключения и без единого сообщения. Ровно то, что
# мы наблюдаем.
#
# Читаем по одному слову из каждой области, помечая на карте, ЧТО именно
# собираемся сделать, — и с запасом по времени, чтобы отметка гарантированно
# легла на диск. Если телефон умрёт, последняя отметка назовёт виновника.
set -u

MARK=/var/log/dreamlte/region-probe.txt

cat > /tmp/rd.py <<'PYEOF'
import mmap, os, sys
addr = int(sys.argv[1], 16)
page = os.sysconf('SC_PAGE_SIZE')
base = addr & ~(page - 1)
fd = os.open('/dev/mem', os.O_RDONLY | os.O_SYNC)
try:
    m = mmap.mmap(fd, page, mmap.MAP_SHARED, mmap.PROT_READ, offset=base)
    print('0x%08x' % int.from_bytes(m[addr - base:addr - base + 4], 'little'))
    m.close()
except Exception as e:
    print('ИСКЛЮЧЕНИЕ: %s' % e)
finally:
    os.close(fd)
PYEOF

note() { echo "$*" >> "$MARK"; sync; }

: > "$MARK"
note "=== проба областей, старт uptime=$(cut -d' ' -f1 /proc/uptime) ==="

# Запас в 8 секунд перед каждым чтением. Наблюдаемое отставание записи на
# карту доходило до 4.5 с, так что меньше брать нельзя — иначе отметка "иду
# читать X" не успеет лечь и мы обвиним не ту область.
probe() {
	local name="$1" addr="$2"
	note ""
	note ">>> СОБИРАЮСЬ ЧИТАТЬ: $name @ $addr"
	sleep 8
	local val
	val="$(python3 /tmp/rd.py "$addr" 2>&1)"
	note "<<< ВЕРНУЛОСЬ: $name @ $addr = $val"
	sleep 2
}

# hci первым как положительный контроль: он заведомо читается, и если
# умрём уже на нём — значит дело не в конкретной области, а в самом факте
# обращения к FSYS0 из этого состояния.
probe "hci (контроль)" 0x11120000
probe "sysreg_fsys0"   0x11020700
probe "unipro"         0x11110000
probe "vs_hci"         0x11121100
probe "ufsp"           0x11130000
probe "phy pma"        0x11124000

note ""
note "=== ВСЕ ОБЛАСТИ ПРОЧИТАНЫ, НИЧЕГО НЕ ПОВИСЛО ==="

echo "############ ЭКСПЕРИМЕНТ 03 ############"
cat "$MARK"
echo "############ КОНЕЦ 03 ############"
